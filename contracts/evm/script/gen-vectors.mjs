// Cross-implementation vectors for the Foundry tests, produced with @plr/shared (packages/shared/dist).
// Run from contracts/evm:  node script/gen-vectors.mjs  (writes test/Vectors.sol; the quotes differ per run: fresh MOCK AK)
import { writeFileSync } from "node:fs";
import { getAddress } from "viem";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  MockRoot, MockTdxAttester, keyHash, registrationNonce, registrationReportData, anchorMessage, toHex, utf8, osMeasurement, parseQuote,
} from "../../../packages/shared/dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
// Fixed deployment the tests reproduce with vm.chainId + deployCodeTo.
const CHAIN_ID = 10143; // Monad testnet
const REGISTRY = "0x5fbdb2315678afecb367f032d93f642f64180aa3";
const OPERATOR = "0x70997970c51812dc3a010c7d01b50e17dc79c8c8";
const OTHER = "0x3c44cdddb6a900fa2b585dd299e03d12fa4293bc";
const contractId = `evm:${CHAIN_ID}:${REGISTRY}`;

const seq = (n, f) => Uint8Array.from({ length: n }, (_, i) => (f + i * 7) & 0xff);
const x = seq(32, 1);
const ed = seq(32, 101);
const compose = utf8('{"plr":"vector"}');
const root = MockRoot.fromSecret(seq(32, 9).map((b, i) => (i === 0 ? 1 : b)));
const att = new MockTdxAttester({ root, composeBytes: compose, instanceId: seq(20, 3) });
const { quote } = await att.getQuote(registrationReportData(x, ed, contractId, OPERATOR));
const { quote: quoteOther } = await att.getQuote(registrationReportData(x, ed, contractId, OTHER));
const { quote: quoteWrongCid } = await att.getQuote(registrationReportData(x, ed, `evm:1:${REGISTRY}`, OPERATOR));
const anchorRoot = seq(32, 55);
const amsg = anchorMessage({ contractId, keyHash: keyHash(x, ed), root: anchorRoot, firstSeq: 0n, count: 3n });

const hex = (b) => `hex"${toHex(b)}"`;
const b32 = (b) => `bytes32(0x${toHex(b)})`;
const src = `// SPDX-License-Identifier: MIT
// GENERATED by script/gen-vectors.mjs from @plr/shared — do not edit.
pragma solidity 0.8.30;

library Vectors {
    uint256 internal constant CHAIN_ID = ${CHAIN_ID};
    address internal constant REGISTRY = ${checksum(REGISTRY)};
    address internal constant OPERATOR = ${checksum(OPERATOR)};
    address internal constant OTHER = ${checksum(OTHER)};
    string internal constant CONTRACT_ID = "${contractId}";
    string internal constant OPERATOR_ID = "${OPERATOR}";
    bytes32 internal constant X25519 = ${b32(x)};
    bytes32 internal constant ED25519 = ${b32(ed)};
    bytes32 internal constant KEY_HASH = ${b32(keyHash(x, ed))};
    bytes32 internal constant REG_NONCE = ${b32(registrationNonce(contractId, OPERATOR))};
    bytes32 internal constant REG_NONCE_NEAR = ${b32(registrationNonce("registry.test.near", "operator.test.near"))};
    bytes32 internal constant COMPOSE_HASH = ${b32(att.composeHash)};
    bytes32 internal constant OS_MEASUREMENT = ${b32(osMeasurement(parseQuote(quote).report))};
    bytes32 internal constant ANCHOR_ROOT = ${b32(anchorRoot)};
    bytes internal constant ROOT_P256 = ${hex(root.publicKey)};
    /// registrationReportData(X25519, ED25519, CONTRACT_ID, OPERATOR_ID), MOCK quote (828 bytes)
    bytes internal constant QUOTE = ${hex(quote)};
    /// bound to OTHER as operator
    bytes internal constant QUOTE_OTHER = ${hex(quoteOther)};
    /// bound to contract id evm:1:<REGISTRY>
    bytes internal constant QUOTE_WRONG_CID = ${hex(quoteWrongCid)};
    /// anchorMessage(CONTRACT_ID, KEY_HASH, ANCHOR_ROOT, 0, 3) (informational: signatures are verified by clients)
    bytes internal constant ANCHOR_MSG = ${hex(amsg)};
}
`;
writeFileSync(join(here, "..", "test", "Vectors.sol"), src);

/** EIP-55 (Solidity requires checksummed address literals). */
function checksum(a) {
  return getAddress(a);
}
