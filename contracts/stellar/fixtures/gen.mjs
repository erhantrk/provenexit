#!/usr/bin/env node
// Cross-implementation vectors for the Soroban registry tests (contracts/stellar/src/test.rs).
// Every value is produced by the TypeScript reference library (@plr/shared, built to packages/shared/dist) and
// @stellar/stellar-sdk (strkeys), so the Rust contract is checked against the TS implementation.
//
// Usage (repo root):  npx tsc -b packages/shared && node contracts/stellar/fixtures/gen.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ed25519, x25519 } from "@noble/curves/ed25519.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { Keypair, StrKey } from "@stellar/stellar-sdk";
import {
  MockRoot, MockTdxAttester, keyHash, registrationNonce, registrationReportData, toHex, utf8, anchorMessage,
} from "../../../packages/shared/dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const seed = (l) => sha256(utf8(`plr-stellar-fixture:${l}`));

const CONTRACT = StrKey.encodeContract(Buffer.from(seed("contract")));
const CONTRACT_ID = `stellar:${CONTRACT}`;
const OPERATOR = Keypair.fromRawEd25519Seed(Buffer.from(seed("operator"))).publicKey();
const STRANGER = Keypair.fromRawEd25519Seed(Buffer.from(seed("stranger"))).publicKey();
const xs = seed("x"), es = seed("e");
const xp = x25519.getPublicKey(xs), ep = ed25519.getPublicKey(es);
const root = MockRoot.fromSecret(seed("root"));
const composeBytes = utf8('{"name":"plr-router-fixture"}\n');
const att = new MockTdxAttester({ root, composeBytes, instanceId: seed("iid").slice(0, 20) });
const { quote } = await att.getQuote(registrationReportData(xp, ep, CONTRACT_ID, OPERATOR));
const { quote: strangerQuote } = await att.getQuote(registrationReportData(xp, ep, CONTRACT_ID, STRANGER));
const kh = keyHash(xp, ep);
const amsg = anchorMessage({ contractId: CONTRACT_ID, keyHash: kh, root: seed("root32"), firstSeq: 0n, count: 3n });
const asig = ed25519.sign(amsg, es);

const bytes = (name, b) => `pub const ${name}: [u8; ${b.length}] = hex!("${toHex(b)}");`;
const str = (name, s) => `pub const ${name}: &str = "${s}";`;
const out = `// GENERATED by fixtures/gen.mjs from @plr/shared — do not edit.
#![allow(dead_code)]
macro_rules! hex {
    ($s:literal) => {{
        const S: &[u8] = $s.as_bytes();
        const N: usize = S.len() / 2;
        const fn nib(c: u8) -> u8 {
            match c {
                b'0'..=b'9' => c - b'0',
                b'a'..=b'f' => c - b'a' + 10,
                _ => panic!("hex"),
            }
        }
        const fn dec() -> [u8; N] {
            let mut o = [0u8; N];
            let mut i = 0;
            while i < N {
                o[i] = (nib(S[2 * i]) << 4) | nib(S[2 * i + 1]);
                i += 1;
            }
            o
        }
        dec()
    }};
}
${str("CONTRACT", CONTRACT)}
${str("CONTRACT_ID", CONTRACT_ID)}
${str("OPERATOR", OPERATOR)}
${str("STRANGER", STRANGER)}
${bytes("X25519", xp)}
${bytes("ED25519", ep)}
${bytes("KEY_HASH", kh)}
${bytes("NONCE_OPERATOR", registrationNonce(CONTRACT_ID, OPERATOR))}
${bytes("NONCE_STRANGER", registrationNonce(CONTRACT_ID, STRANGER))}
${bytes("COMPOSE_HASH", sha256(composeBytes))}
${bytes("ROOT_P256", root.publicKey)}
${bytes("QUOTE", quote)}
${bytes("QUOTE_STRANGER", strangerQuote)}
${bytes("ANCHOR_ROOT", seed("root32"))}
${bytes("ANCHOR_SIG", asig)}
`;
writeFileSync(join(here, "..", "src", "vectors.rs"), out);
console.log("wrote src/vectors.rs");
