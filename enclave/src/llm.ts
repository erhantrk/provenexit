/**
 * Upstream LLM client. The LLM is reached ONLY at 127.0.0.1 (SPEC §6 no-retention rules); the host name is
 * not configurable. Requests are always `stream: true`; the response is consumed as OpenAI-style SSE.
 */
import http from "node:http";
import { PlrError } from "@plr/shared";
import { SseParser } from "./sse.js";
import { isPlainObject, type ChatRequest } from "./validate.js";

/**
 * The exact upstream request: the validated chat fields, `stream: true` forced, and `cache_prompt: false` so
 * llama-server never reuses the previous request's KV cache (a reused prefix shows up as `timings.cache_n` and
 * as faster prompt processing — a token-level oracle on another user's prompt). The host also launches
 * llama-server with prompt caching disabled; this is defence in depth.
 */
export function upstreamBody(req: ChatRequest): ChatRequest & { stream: true; cache_prompt: false } {
  return { ...req, stream: true, cache_prompt: false };
}

/** Per-boot LLM API key generated by the host: 32 random bytes as lowercase hex. */
export const LLM_API_KEY_RE = /^[0-9a-f]{64}$/;

export interface LlmClient {
  /**
   * Starts a streaming completion. Resolves once the upstream accepted the request (HTTP 200 SSE); the
   * iterable then yields content deltas and throws PlrError("E_UPSTREAM") if the stream fails or ends
   * without a finish. Rejects with PlrError("E_UPSTREAM") if the upstream is unreachable or refuses.
   */
  chat(req: ChatRequest, signal: AbortSignal): Promise<AsyncIterable<string>>;
}

export const LLM_HOST = "127.0.0.1";
const MAX_UPSTREAM_BYTES = 64 * 1024 * 1024;
const MAX_ERROR_DRAIN = 64 * 1024;

function upstreamError(): PlrError {
  return new PlrError("E_UPSTREAM");
}

/** Parses one SSE `data:` payload. Returns the content delta (possibly ""), "done", or "finish". */
function parseChunk(data: string): { content: string; finished: boolean; done: boolean } {
  if (data === "[DONE]") return { content: "", finished: false, done: true };
  let o: unknown;
  try {
    o = JSON.parse(data);
  } catch {
    throw upstreamError();
  }
  if (!isPlainObject(o) || o.error !== undefined) throw upstreamError();
  const choices = o.choices;
  if (!Array.isArray(choices)) throw upstreamError();
  if (choices.length === 0) return { content: "", finished: false, done: false }; // e.g. usage-only chunk
  const c0: unknown = choices[0];
  if (!isPlainObject(c0)) throw upstreamError();
  let content = "";
  const delta = c0.delta;
  if (delta !== undefined && delta !== null) {
    if (!isPlainObject(delta)) throw upstreamError();
    if (typeof delta.content === "string") content = delta.content;
    else if (delta.content !== undefined && delta.content !== null) throw upstreamError();
  }
  const fr = c0.finish_reason;
  if (fr !== undefined && fr !== null && typeof fr !== "string") throw upstreamError();
  return { content, finished: typeof fr === "string", done: false };
}

export class HttpLlmClient implements LlmClient {
  readonly #port: number;
  readonly #timeoutMs: number;
  readonly #authHeader: Record<string, string>;

  /**
   * @param opts.apiKey per-boot LLM API key from the host (64 hex); sent as `Authorization: Bearer`, so no
   *   other local process can use (or probe) the LLM.
   */
  constructor(port: number, opts: { timeoutMs?: number; apiKey?: string | null } = {}) {
    if (!Number.isSafeInteger(port) || port < 1 || port > 65535) throw new PlrError("E_BAD_INPUT", "llm port");
    this.#port = port;
    this.#timeoutMs = opts.timeoutMs ?? 300_000;
    const key = opts.apiKey ?? null;
    if (key !== null && !LLM_API_KEY_RE.test(key)) throw new PlrError("E_BAD_INPUT", "llm api key");
    this.#authHeader = key === null ? {} : { authorization: `Bearer ${key}` };
  }

  chat(req: ChatRequest, signal: AbortSignal): Promise<AsyncIterable<string>> {
    const body = Buffer.from(JSON.stringify(upstreamBody(req)), "utf8");
    const combined = AbortSignal.any([signal, AbortSignal.timeout(this.#timeoutMs)]);
    return new Promise((resolve, reject) => {
      const r = http.request(
        {
          host: LLM_HOST,
          port: this.#port,
          path: "/v1/chat/completions",
          method: "POST",
          headers: { "content-type": "application/json", "content-length": body.length, accept: "text/event-stream", ...this.#authHeader },
          signal: combined,
          agent: false,
        },
        (res) => {
          const ctype = String(res.headers["content-type"] ?? "");
          if (res.statusCode !== 200 || !ctype.toLowerCase().startsWith("text/event-stream")) {
            let n = 0;
            res.on("data", (c: Buffer) => {
              n += c.length;
              if (n > MAX_ERROR_DRAIN) res.destroy();
            });
            res.on("error", () => undefined);
            res.resume();
            reject(upstreamError());
            return;
          }
          resolve(stream(res));
        },
      );
      r.on("error", () => reject(upstreamError()));
      r.end(body);
    });
  }
}

async function* stream(res: http.IncomingMessage): AsyncGenerator<string> {
  const parser = new SseParser();
  let total = 0;
  let finished = false;
  let done = false;
  try {
    for await (const chunk of res as AsyncIterable<Buffer>) {
      total += chunk.length;
      if (total > MAX_UPSTREAM_BYTES) throw upstreamError();
      let events: string[];
      try {
        events = parser.push(chunk);
      } catch {
        throw upstreamError();
      }
      for (const data of events) {
        if (done) break;
        const c = parseChunk(data);
        if (c.done) done = true;
        if (c.finished) finished = true;
        if (c.content !== "") yield c.content;
      }
      if (done) break;
    }
    if (!done) {
      for (const data of parser.end()) {
        const c = parseChunk(data);
        if (c.done) done = true;
        if (c.finished) finished = true;
        if (c.content !== "") yield c.content;
      }
    }
  } catch {
    throw upstreamError();
  } finally {
    res.destroy();
  }
  if (!finished && !done) throw upstreamError();
}
